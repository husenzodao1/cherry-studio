// Generates the alternative launcher icons from src/web/app-icons.json:
// - res/drawable/ic_alt_<id>_bg.xml (gradient) and _fg.xml (white line drawing in the 66dp safe zone)
// - res/mipmap-anydpi-v26/ic_alt_<id>.xml (adaptive icon, with a monochrome layer for themed icons)
// - res/mipmap-anydpi/ic_alt_<id>.xml (layered icon for Android 7)
// - the <activity-alias> entries in AndroidManifest.xml (between the APP-ICONS markers)
// Run: node tools/android/app-icons.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../../', import.meta.url)
const res = new URL('android/app/src/main/res/', root)
const { icons } = JSON.parse(readFileSync(new URL('src/web/app-icons.json', root), 'utf8'))
const argb = (hex) => `#FF${hex.slice(1).toUpperCase()}`
const out = (dir, name, text) => {
  const d = new URL(`${dir}/`, res)
  mkdirSync(d, { recursive: true })
  writeFileSync(new URL(name, d), text)
}
const head = '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/android/app-icons.mjs from src/web/app-icons.json -->\n'

const fg = (d, color) => `${head}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="30" android:translateY="30" android:scaleX="2" android:scaleY="2">
        <path android:pathData="${d}" android:fillColor="#00000000" android:strokeColor="${color}"
            android:strokeWidth="1.6" android:strokeLineCap="round" android:strokeLineJoin="round" />
    </group>
</vector>
`
const bg = (from, to) => `${head}<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="${argb(from)}" />
                <item android:offset="1" android:color="${argb(to)}" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M54,-10a64,64 0,0 1,64 64h-128a64,64 0,0 1,64 -64z" android:fillColor="#14FFFFFF" />
</vector>
`

for (const i of icons) {
  out('drawable', `ic_alt_${i.id}_fg.xml`, fg(i.d, '#FFFFFFFF'))
  out('drawable', `ic_alt_${i.id}_mono.xml`, fg(i.d, '#FF000000'))
  out('drawable', `ic_alt_${i.id}_bg.xml`, bg(i.from, i.to))
  out('mipmap-anydpi-v26', `ic_alt_${i.id}.xml`, `${head}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_alt_${i.id}_bg" />
    <foreground android:drawable="@drawable/ic_alt_${i.id}_fg" />
    <monochrome android:drawable="@drawable/ic_alt_${i.id}_mono" />
</adaptive-icon>
`)
  out('mipmap-anydpi', `ic_alt_${i.id}.xml`, `${head}<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/ic_alt_${i.id}_bg" />
    <item android:drawable="@drawable/ic_alt_${i.id}_fg" />
</layer-list>
`)
}

const launcher = `                <intent-filter>
                    <action android:name="android.intent.action.MAIN" />
                    <category android:name="android.intent.category.LAUNCHER" />
                </intent-filter>`
const alias = (name, icon, enabled) => `        <activity-alias
            android:name=".${name}"
            android:enabled="${enabled}"
            android:exported="true"
            android:icon="${icon}"
            android:roundIcon="${icon}"
            android:label="@string/title_activity_main"
            android:targetActivity=".MainActivity">
${launcher}
        </activity-alias>`
const block = ['        <!-- APP-ICONS:START (tools/android/app-icons.mjs) — one launcher entry per icon; AppIconPlugin enables one -->',
  alias('IconDefault', '@mipmap/ic_launcher', true),
  ...icons.map((i) => alias(`Icon_${i.id}`, `@mipmap/ic_alt_${i.id}`, false)),
  '        <!-- APP-ICONS:END -->'].join('\n')
const manifestUrl = new URL('android/app/src/main/AndroidManifest.xml', root)
let manifest = readFileSync(manifestUrl, 'utf8')
manifest = /<!-- APP-ICONS:START[\s\S]*?APP-ICONS:END -->/.test(manifest)
  ? manifest.replace(/ {8}<!-- APP-ICONS:START[\s\S]*?APP-ICONS:END -->/, block)
  : manifest.replace(/(\n {8}<provider)/, `\n${block}\n$1`)
writeFileSync(manifestUrl, manifest)
console.log(`${icons.length} icons written`)
